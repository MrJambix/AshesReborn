"""server/worldd/items/reward_boxes.h: which reward table the choose-one window of each reward box lists.

An item whose activation is OpenRewardSelection names its table in RewardSelectionDataId.  contentc does not compile that field (item_box holds ActivationLootBoxData, another set of items), and
worldd cannot read the compressed design records, so this script reads them from content.db and writes the pairs.  Every table must be one loot_table holds, listing at least one item and no variation.

    python tools/worldd/gen_reward_boxes.py [--content-db PATH]     # rewrite the header
    python tools/worldd/gen_reward_boxes.py --check                 # write nothing, exit 1 on a change
"""
import argparse
import gzip
import json
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, 'server', 'worldd', 'items', 'reward_boxes.h')


def boxes(path):
    db = sqlite3.connect('file:%s?mode=ro' % path.replace('\\', '/'), uri=True)
    out = []
    for name, guid, data in db.execute("SELECT name, guid, data FROM record WHERE schema = 'ItemRecordBase' ORDER BY guid"):
        if isinstance(data, bytes) and data[:2] == b'\x1f\x8b':
            data = gzip.decompress(data)
        table = (json.loads(data).get('RewardSelectionDataId') or {}).get('Guid', 0)
        if not table:
            continue
        row = db.execute('SELECT data FROM loot_table WHERE guid = ?', (table,)).fetchone()
        if not row:
            sys.exit('%s: the reward table %d is not in loot_table' % (name, table))
        items = [i for c in json.loads(row[0]).get('c', []) for r in c.get('r', []) for i in r.get('items', [])]
        if not items or any(i.get('var') for i in items):
            sys.exit('%s: the reward table %d lists no items, or one with a variation' % (name, table))
        out.append((guid, table, name, len(items)))
    return out


def render(rows):
    lines = ['''// SPDX-License-Identifier: AGPL-3.0-only
// Part of a modified SandalCore deployment (branch vps-deploy); not the original project or endorsed by Cyb.
// ============================================================================
//  items/reward_boxes.h: the reward table the choose-one window of each reward box lists
//
//  GENERATED by tools/worldd/gen_reward_boxes.py from content.db's design records; do not edit.
// ============================================================================
#pragma once

#include <cstdint>

namespace aoc::worldd::items {

struct RewardBox {
    int64_t item;    // the box's item record
    int64_t table;   // its RewardSelectionDataId
};

inline constexpr RewardBox kRewardBoxes[] = {''']
    for guid, table, name, items in rows:
        lines.append('    {%dll, %dll},   // %s (%d item%s)' % (guid, table, name, items, '' if items == 1 else 's'))
    lines.append('''};

/// The table the box lists; 0 for an item that is no reward box.
inline int64_t reward_box_table(int64_t item) {
    for (const RewardBox& b : kRewardBoxes) {
        if (b.item == item) return b.table;
    }
    return 0;
}

}  // namespace aoc::worldd::items
''')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--content-db', default=os.path.join(ROOT, 'dist', 'content', 'content.db'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    rows = boxes(a.content_db)
    print('%d reward boxes' % len(rows))
    text = render(rows)
    old = open(HEADER, newline='').read() if os.path.exists(HEADER) else None
    same = old is not None and old.replace('\r\n', '\n') == text
    if a.check:
        print('reward_boxes.h: ' + ('unchanged' if same else 'WOULD CHANGE'))
        sys.exit(0 if same else 1)
    if same:
        print('reward_boxes.h: unchanged')
        return
    with open(HEADER, 'w', newline='') as f:
        f.write(text)
    print('reward_boxes.h: updated')


if __name__ == '__main__':
    main()
