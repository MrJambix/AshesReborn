"""Writes server/worldd/quest/destiny_table.h from dist/content/content.db.

The Destiny board is quests, and contentc compiles those, but not what the board needs of the raw records: the DestinySystem
record's six tracks, which quest a SubQuest objective starts, and the filters of the Gather, Kill, UseAbility, CompleteQuest and
SkillTreeChange objectives.  Only Destiny quests are listed, so no other quest changes behaviour.  Run from the repository root.
"""
import gzip
import json
import sqlite3
import sys

DB = "dist/content/content.db"
OUT = "server/worldd/quest/destiny_table.h"
RARITY = {"Common": 0, "Uncommon": 1, "Rare": 2, "Heroic": 3, "Epic": 4, "Legendary": 5, "Artifact": 6}


def cpp_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    db = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)

    def record(guid):
        row = db.execute("select data from record where guid = ?", (guid,)).fetchone()
        return json.loads(gzip.decompress(row[0])) if row else {}

    system = json.loads(gzip.decompress(db.execute("select data from record where schema = 'DestinySystem'").fetchone()[0]))
    item_tags = db.execute("select item_guid, tag from item_tag").fetchall()

    tracks = []
    for t in system["DestinyTrackDataArray"]:
        tracks.append((t["DestinyTrackQuest"]["Guid"], t["DestinyTrackSkillTree"]["Guid"], [m["Guid"] for m in t["MilestoneRewardObjectives"]]))

    links, kills, gathers, abilities, completes, skills = [], [], [], [], [], []
    for guid, name, kind in db.execute("select o.guid, o.name, o.obj_type from quest_objective o join quest q on q.guid = o.quest_guid where q.flavor = 'Destiny' order by o.guid"):
        d = record(guid)
        if kind == "SubQuest":
            info = d.get("SubQuestInfo") or {}
            child = (info.get("SubQuest") or {}).get("Guid", 0)
            if child:
                links.append((guid, child, name))
        elif kind == "Kill":
            kills.append((guid, name))
        elif kind == "Gather":
            f = (d.get("GatherableObjectiveData") or {}).get("Filter") or {}
            tags = [t["TagName"].lower() for t in (f.get("Tags") or {}).get("TagDictionary") or []]
            rarities = [RARITY[r.split("::")[1]] for r in f.get("ItemRarities") or [] if r.split("::")[1] in RARITY]
            items = sorted({g for g, tag in item_tags if any(tag.lower() == t or tag.lower().startswith(t + ".") for t in tags)} | {i["Guid"] for i in f.get("ItemsIds") or []})
            gathers.append((guid, min(rarities) if rarities else 0, items, name))
        elif kind == "UseAbility":
            u = d.get("AbilityUseData") or {}
            tags = u.get("RequiredAbilityTags") or []
            tags = [t["TagName"] if isinstance(t, dict) else t for t in tags]
            if tags:
                abilities.append((guid, tags, bool(u.get("bMustBeInCombat")), name))
        elif kind == "CompleteQuest":
            flavors = [x.split("::")[1] for x in (d.get("CompleteQuestObjectiveData") or {}).get("QuestFlavorFilters") or []]
            completes.append((guid, flavors, name))
        elif kind == "SkillTreeChange":
            types = [x["Guid"] for x in (d.get("SkillTreeChangeData") or {}).get("AllowedLevelingTypes") or []]
            skills.append((guid, types, name))

    out = ["// SPDX-License-Identifier: AGPL-3.0-only", "// Copyright (C) 2026 Cyb and contributors. Developed by Cyb; thanks to Hatemost and CoA (Creation of Ashes).",
           "// Generated by tools/worldd/gen_destiny.py from content.db.  Do not edit.", "#pragma once", "", "#include <cstdint>", "#include <initializer_list>", "#include <string_view>", "",
           "namespace aoc::worldd::quest::destiny {", ""]
    out += ["struct Track {", "    int64_t quest;      // the track's root quest", "    int64_t tree;       // its skill tree", "    int64_t milestones[4];   // MilestoneRewardObjectives (0: none)", "};", "inline constexpr Track kTracks[] = {"]
    for q, tree, ms in tracks:
        ms4 = (ms + [0, 0, 0, 0])[:4]
        out.append(f"    {{{q}ll, {tree}ll, {{{', '.join(str(m) + 'll' for m in ms4)}}}}},")
    out += ["};", "", "/// A SubQuest objective -> the quest it starts (AutoGrant) and waits for.", "struct SubQuestLink {", "    int64_t objective, quest;", "};", "inline constexpr SubQuestLink kSubQuests[] = {"]
    for o, child, name in links:
        out.append(f"    {{{o}ll, {child}ll}},   // {name}")
    out += ["};", "", "/// The Kill objectives whose creatures are named by a tag query the server does not model: any creature counts.", "inline constexpr int64_t kAnyKill[] = {"]
    for o, name in kills:
        out.append(f"    {o}ll,   // {name}")
    out += ["};", "", "/// The items a Gather objective counts, by its filter's tags, from its rarity up."]
    for i, (o, rarity, items, name) in enumerate(gathers):
        out.append(f"inline constexpr int64_t kGatherItems{i}[] = {{{', '.join(str(x) + 'll' for x in items) or '0ll'}}};   // {name}")
    out += ["struct GatherFilter {", "    int64_t objective;", "    int min_rarity;", "    const int64_t* items;", "    int count;", "};", "inline constexpr GatherFilter kGather[] = {"]
    for i, (o, rarity, items, name) in enumerate(gathers):
        out.append(f"    {{{o}ll, {rarity}, kGatherItems{i}, {len(items)}}},")
    out += ["};", "", "/// A UseAbility objective that names ability tags rather than abilities.", "struct AbilityFilter {", "    int64_t objective;", "    std::string_view tags[3];", "    bool in_combat;", "};", "inline constexpr AbilityFilter kAbilityTags[] = {"]
    for o, tags, combat, name in abilities:
        tags3 = (tags + ["", "", ""])[:3]
        out.append(f"    {{{o}ll, {{{', '.join(cpp_str(t) for t in tags3)}}}, {'true' if combat else 'false'}}},   // {name}")
    out += ["};", "", "/// A CompleteQuest objective: the quest flavors it counts (none listed: any).", "struct CompleteFilter {", "    int64_t objective;", "    std::string_view flavors[3];", "};", "inline constexpr CompleteFilter kComplete[] = {"]
    for o, flavors, name in completes:
        f3 = (flavors + ["", "", ""])[:3]
        out.append(f"    {{{o}ll, {{{', '.join(cpp_str(x) for x in f3)}}}}},   // {name}")
    out += ["};", "", "/// A SkillTreeChange objective: the leveling types it counts."]
    for i, (o, types, name) in enumerate(skills):
        out.append(f"inline constexpr int64_t kSkillTypes{i}[] = {{{', '.join(str(x) + 'll' for x in types) or '0ll'}}};   // {name}")
    out += ["struct SkillFilter {", "    int64_t objective;", "    const int64_t* types;", "    int count;", "};", "inline constexpr SkillFilter kSkill[] = {"]
    for i, (o, types, name) in enumerate(skills):
        out.append(f"    {{{o}ll, kSkillTypes{i}, {len(types)}}},")
    out += ["};", "", "}  // namespace aoc::worldd::quest::destiny", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{OUT}: {len(tracks)} tracks, {len(links)} sub-quests, {len(kills)} kills, {len(gathers)} gathers ({sum(len(g[2]) for g in gathers)} items), {len(abilities)} ability filters, {len(completes)} completes, {len(skills)} skill filters")
    return 0


if __name__ == "__main__":
    sys.exit(main())
